const GLYPHS = new Map<string, boolean[][]>(
  Object.entries(RAW).map(([ch, rows]) => [ch, rows.split("|").map((row) => [...row].map((c) => c === "#"))]),
);

const FALLBACK = GLYPHS.get("?")!;

/**
 * Glyph for a character. Slovak and Czech letters have their own glyphs;
 * other letters with diacritics fall back to their base letter.
 */
export function glyph(ch: string): boolean[][] {
  const direct = GLYPHS.get(ch);
  if (direct) return direct;
  const base = ch.normalize("NFD").replace(/\p{M}/gu, "");
  return GLYPHS.get(base) ?? FALLBACK;
}

export function hasGlyph(ch: string): boolean {
  return GLYPHS.has(ch) || GLYPHS.has(ch.normalize("NFD").replace(/\p{M}/gu, ""));
}

/** Width in pixels of a single line of text (no trailing spacing). */
export function textWidth(text: string): number {
  const n = [...text].length;
  return n === 0 ? 0 : n * GLYPH_ADVANCE - 1;
}

/**
 * Word-wrap text into lines that fit `maxWidth` pixels. Words longer than a
 * line are broken. Returns the lines and whether everything fit in
 * `maxHeight` pixels.
 */
export function wrapText(text: string, maxWidth: number, maxHeight: number): { lines: string[]; fits: boolean } {
  const perLine = Math.max(0, Math.floor((maxWidth + 1) / GLYPH_ADVANCE));
  const maxLines = Math.max(0, Math.floor((maxHeight + 1) / LINE_HEIGHT));
  const lines: string[] = [];
  if (perLine === 0) return { lines, fits: text.trim().length === 0 };

  for (const paragraph of text.split(/\r?\n/)) {
    let line = "";
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      let rest = [...word];
      while (rest.length > 0) {
        const candidate = line ? `${line} ${rest.join("")}` : rest.join("");
        if ([...candidate].length <= perLine) {
          line = candidate;
          rest = [];
        } else if (line) {
          lines.push(line);
          line = "";
        } else {
          lines.push(rest.slice(0, perLine).join(""));
          rest = rest.slice(perLine);
        }
      }
    }
    lines.push(line);
  }
  while (lines.length > 0 && lines[lines.length - 1] === "") lines.pop();
  return { lines, fits: lines.length <= maxLines };
}

/**
 * Draw text with the pixel font through a `plot(x, y)` callback, so it works
 * for server rasters and browser canvases alike.
 */
export function drawText(
  text: string,
  originX: number,
  originY: number,
  plot: (x: number, y: number) => void,
  scale = 1,
): void {
  let cx = originX;
  for (const ch of text) {
    const g = glyph(ch);
    for (let gy = 0; gy < GLYPH_HEIGHT; gy++) {
      for (let gx = 0; gx < GLYPH_WIDTH; gx++) {
        if (!g[gy][gx]) continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) plot(cx + gx * scale + sx, originY + gy * scale + sy);
        }
      }
    }
    cx += GLYPH_ADVANCE * scale;
  }
}
